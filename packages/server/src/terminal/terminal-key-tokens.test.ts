import { expect, it } from "vitest";
import { resolveTerminalKeyToken } from "./terminal-key-tokens.js";

// Upstream's send_terminal_keys cases (d0fd2e532 mcp-server.test.ts:1303-1352).
it.each<[string, string, string, boolean]>([
  ["Down", "\x1b[B", "", false],
  ["Up", "\x1b[A", "", false],
  ["Left", "\x1b[D", "", false],
  ["Right", "\x1b[C", "", false],
  ["PageUp", "\x1b[5~", "", false],
  ["PageDown", "\x1b[6~", "", false],
  ["Home", "\x1b[H", "", false],
  ["End", "\x1b[F", "", false],
  ["Insert", "\x1b[2~", "", false],
  ["Delete", "\x1b[3~", "", false],
  ["F1", "\x1bOP", "", false],
  ["F5", "\x1b[15~", "", false],
  ["F12", "\x1b[24~", "", false],
  ["S-Tab", "\x1b[Z", "", false],
  ["C-r", "\x12", "", false],
  ["M-b", "\x1bb", "", false],
  ["C-M-Left", "\x1b[1;7D", "", false],
  ["C-S-Up", "\x1b[1;6A", "", false],
  ["C-Space", "\x00", "", false],
  ["Enter", "\r", "", false],
  ["Tab", "\t", "", false],
  ["Escape", "\x1b", "", false],
  ["Space", " ", "", false],
  ["BSpace", "\x7f", "", false],
  ["C-c", "\x03", "", false],
  ["C-d", "\x04", "", false],
  ["C-z", "\x1a", "", false],
  ["C-l", "\x0c", "", false],
  ["C-a", "\x01", "", false],
  ["C-e", "\x05", "", false],
  ["Down", "\x1bOB", "\x1b[?1h", false],
  ["S-Enter", "\x1b[13;2u", "\x1b[=1;1u", false],
  ["C-Enter", "\x1b[13;28;13;1;8;1_", "\x1b[?9001h", false],
  ["echo hello\r", "echo hello\r", "", false],
  ["\x1b[B", "\x1b[B", "", false],
  ["UnknownKey", "UnknownKey", "", false],
  ["constructor", "constructor", "", false],
  ["__proto__", "__proto__", "", false],
  ["", "", "", false],
  ["Down", "Down", "\x1b[?1h", true],
  ["C-r", "C-r", "", true],
  ["S-Tab", "S-Tab", "", true],
])("encodes terminal token %j as %j (preamble=%j, literal=%s)", (key, data, preamble, literal) => {
  expect(resolveTerminalKeyToken({ key, literal, preamble })).toBe(data);
});
