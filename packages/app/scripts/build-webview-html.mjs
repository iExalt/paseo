import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { hashWebViewSources } from "./webview-source-hash.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(appRoot, "../..");

// Each WebView page is one bundled script in a committed HTML string. `sources` exports a
// hash of the page's app sources and bundled package versions, which a unit test
// recomputes to catch a stale bundle. Workspace packages count by version only.
const WEBVIEWS = [
  {
    name: "terminal",
    entry: "src/terminal/webview/terminal-emulator-webview-entry.ts",
    output: "src/terminal/webview/terminal-emulator-webview-html.ts",
    exportName: "terminalEmulatorWebViewHtml",
    minify: false,
    sources: "terminalEmulatorWebViewSources",
  },
  {
    name: "file editor",
    entry: "src/file-pane/editor/webview/entry.ts",
    output: "src/file-pane/editor/webview/file-editor-webview-html.ts",
    exportName: "fileEditorWebViewHtml",
    minify: true,
    sources: "fileEditorWebViewSources",
  },
];

async function resolveTsPath(basePath) {
  const candidates = [
    basePath,
    `${basePath}.ts`,
    `${basePath}.tsx`,
    `${basePath}.js`,
    `${basePath}.jsx`,
    path.join(basePath, "index.ts"),
    path.join(basePath, "index.tsx"),
    path.join(basePath, "index.js"),
    path.join(basePath, "index.jsx"),
  ];
  for (const candidate of candidates) {
    try {
      const stat = await fs.stat(candidate);
      if (stat.isFile()) return candidate;
    } catch {
      // try next candidate
    }
  }
  return basePath;
}

const aliasPlugin = {
  name: "paseo-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, async (args) => ({
      path: await resolveTsPath(path.join(appRoot, "src", args.path.slice(2))),
    }));
    build.onResolve({ filter: /^@server\// }, async (args) => ({
      path: await resolveTsPath(
        path.join(repoRoot, "packages/server/src", args.path.slice("@server/".length)),
      ),
    }));
  },
};

/** The package an input outside the app's sources belongs to, such as `../../node_modules/@scope/name`. */
function packageDir(input) {
  const parts = input.split("/");
  const modules = parts.lastIndexOf("node_modules");
  if (modules >= 0) {
    const scoped = parts[modules + 1].startsWith("@");
    return parts.slice(0, modules + (scoped ? 3 : 2)).join("/");
  }
  // A workspace package, such as `../highlight/dist/index.js`.
  return parts.slice(0, parts.lastIndexOf("..") + 2).join("/");
}

async function buildWebView(webview) {
  const result = await esbuild.build({
    entryPoints: [path.join(appRoot, webview.entry)],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["ios15", "chrome100"],
    loader: {
      ".css": "text",
    },
    minify: webview.minify,
    metafile: webview.sources !== null,
    plugins: [aliasPlugin],
    logLevel: "info",
  });

  const js = result.outputFiles[0]?.text;
  if (!js) {
    throw new Error(`${webview.name} webview bundle produced no JavaScript`);
  }

  const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover"
    />
  </head>
  <body>
    <script>${js}</script>
  </body>
</html>`;

  let contents = `// Generated by packages/app/scripts/build-webview-html.mjs.
// Do not edit by hand.

export const ${webview.exportName} = ${JSON.stringify(html)};
`;
  if (webview.sources) {
    const inputs = Object.keys(result.metafile.inputs).map((input) =>
      path.relative(appRoot, path.resolve(process.cwd(), input)),
    );
    const files = inputs.filter((file) => file.startsWith("src/")).sort();
    const packages = [
      ...new Set(inputs.filter((file) => !file.startsWith("src/")).map(packageDir)),
    ].sort();
    const hash = await hashWebViewSources(appRoot, files, packages);
    contents += `
export const ${webview.sources} = ${JSON.stringify({ files, packages, hash }, null, 2)};
`;
  }

  const output = path.join(appRoot, webview.output);
  await fs.writeFile(output, contents);
  console.log(`Wrote ${path.relative(repoRoot, output)} (${html.length} bytes)`);
}

for (const webview of WEBVIEWS) await buildWebView(webview);
