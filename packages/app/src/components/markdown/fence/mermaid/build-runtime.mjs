import esbuild from "esbuild";
import fs from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "../../../../..");
const repoRoot = path.resolve(appRoot, "../..");
const entry = path.join(__dirname, "runtime/entry.ts");
const output = path.join(__dirname, "runtime/html.gen.ts");
const repoRequire = createRequire(import.meta.url);
const mermaidManifest = repoRequire.resolve("mermaid/package.json");
const mermaidRequire = createRequire(mermaidManifest);
const { version } = repoRequire(mermaidManifest);
// Mermaid ships this upstream js-yaml release inside its compiled core.
const embeddedYamlVersion = { "12.4.0": "4.3.2" }[version];
if (!embeddedYamlVersion) {
  throw new Error(`Confirm the js-yaml notice bundled by Mermaid ${version}`);
}

async function dependencyNotice(name, licenseFile) {
  const packageRoot = path.resolve(path.dirname(mermaidRequire.resolve(name)), "..");
  const { version: dependencyVersion } = repoRequire(path.join(packageRoot, "package.json"));
  const text = await fs.readFile(path.join(packageRoot, licenseFile), "utf8");
  return `/*! ${name} ${dependencyVersion}\n${text.trim()}\n*/`;
}

const yamlLicense = (
  await fs.readFile(path.join(__dirname, "runtime/js-yaml.LICENSE"), "utf8")
).trim();
const notices = [
  `/*! js-yaml ${embeddedYamlVersion}\n${yamlLicense}\n*/`,
  ...(await Promise.all([
    dependencyNotice("elkjs", "LICENSE.md"),
    dependencyNotice("katex", "LICENSE"),
  ])),
];

const target = ["ios15", "chrome100"];
const compat = await esbuild.transform(
  await fs.readFile(path.join(__dirname, "runtime/compat.ts"), "utf8"),
  { loader: "ts", format: "iife", target, minify: true },
);

const result = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target,
  minify: true,
  banner: { js: [...notices, compat.code].join("\n") },
  logLevel: "info",
});

const rawJs = result.outputFiles[0]?.text;
if (!rawJs) {
  throw new Error("Mermaid runtime bundle produced no JavaScript");
}
// JSON.stringify below escapes the TypeScript representation, not the runtime
// HTML — an embedded closing-script sequence would still terminate the inline
// <script>. `<\/script` is identical to `</script` inside JS strings/regex.
const js = rawJs.replace(/<\/script/gi, "<\\/script");

const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta
      http-equiv="Content-Security-Policy"
      content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'; img-src data: blob:; font-src 'none'; media-src 'none'; object-src 'none'; frame-src 'none'; base-uri 'none'; form-action 'none'"
    />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover"
    />
    <style>
      html,
      body {
        margin: 0;
        padding: 0;
        background: transparent;
        height: 100%;
      }
      /* The host sizes this frame to the diagram, so the diagram fills the frame. */
      #diagram {
        height: 100%;
      }
      #diagram svg {
        display: block;
      }
      /* Keep Mermaid's temporary render container unscaled when the host mounts this frame
         at 0x0 or 240x240 before the diagram's own dimensions are known. */
      #staging-clip {
        position: fixed;
        width: 0;
        height: 0;
        overflow: hidden;
        visibility: hidden;
        pointer-events: none;
      }
      #staging {
        width: 16384px;
        height: 16384px;
      }
    </style>
  </head>
  <body>
    <div id="diagram"></div>
    <div id="staging-clip" aria-hidden="true"><div id="staging"></div></div>
    <script>${js}</script>
  </body>
</html>`;

const contents = `// Generated by packages/app/src/components/markdown/fence/mermaid/build-runtime.mjs.
// Mermaid ${version} from the workspace lockfile. Do not edit by hand.

export const mermaidRuntimeHtml = ${JSON.stringify(html)};
`;

await fs.writeFile(output, contents);
console.log(`Wrote ${path.relative(repoRoot, output)} (${html.length} bytes)`);
